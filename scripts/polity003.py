"""Polity-003: graded friction measurement on a wider unauthored-conflict polity.

The arena (round dynamics, network, protocol) is the project's. The conflict
content in docs/polity-003/minds.json was generated by four separate subagent
minds (marketplace, debt, workplace, tenancy domains) under opposed mandates;
the 9-pair counterpart graph supersedes polity-002's 4-pair topology, breaking
delta saturation so the measurement grades legislative coverage instead of
reading binary resolution.
"""

import json
from pathlib import Path

from law_and_order import RuleSet
from law_and_order.protocol import Phase
from law_and_order.sim.engine import CRITICAL_FRICTION, WINDOW, run
from law_and_order.sim.population import Persona

ROUNDS = 60
SEED = 7
ROOT = Path(__file__).resolve().parent.parent

NONSENSE_CLAIMS = (
    "alpha beta gamma delta",
    "epsilon zeta eta theta",
    "iota kappa lambda mu",
    "nu xi omicron pi",
)
NONSENSE_NOISE = ("rho sigma tau", "upsilon phi chi", "psi omega alpha")


def load_population() -> tuple[Persona, ...]:
    minds = json.loads((ROOT / "docs" / "polity-003" / "minds.json").read_text(encoding="utf-8"))
    return tuple(
        Persona(
            name=name,
            claims=tuple(mind["claims"]),
            noise=tuple(mind["noise"]),
            counterparts=tuple(mind["counterparts"]),
        )
        for name, mind in minds.items()
    )


def reduced_v2(full: RuleSet) -> RuleSet:
    kept = tuple(rule for rule in full.ordered() if rule.rule_id != "R7")
    return RuleSet(rules=kept)


def nonsense_population(real: tuple[Persona, ...]) -> tuple[Persona, ...]:
    return tuple(
        Persona(
            name=persona.name,
            claims=NONSENSE_CLAIMS[: len(persona.claims)],
            noise=NONSENSE_NOISE[: len(persona.noise)],
            counterparts=persona.counterparts,
        )
        for persona in real
    )


def measure(population, ruleset):
    baseline, _, _ = run(population, ROUNDS, SEED)
    installed, published, resolved = run(
        population, ROUNDS, SEED, installed=True, ruleset=ruleset
    )
    baseline_tail = sum(record.friction for record in baseline[-WINDOW:]) / WINDOW
    installed_tail = sum(record.friction for record in installed[-WINDOW:]) / WINDOW
    return baseline_tail, installed_tail, baseline_tail - installed_tail, len(published), resolved


def main() -> None:
    population = load_population()
    ruleset = RuleSet.from_json((ROOT / "rulesets" / "v2.json").read_text(encoding="utf-8"))

    baseline_tail, installed_tail, delta, rulings, resolved = measure(population, ruleset)
    baseline_phase = Phase.ORDERED if baseline_tail < CRITICAL_FRICTION else Phase.DISORDERED
    installed_phase = Phase.ORDERED if installed_tail < CRITICAL_FRICTION else Phase.DISORDERED

    print(f"baseline tail friction:   {baseline_tail:.3f}  ({baseline_phase.value})")
    print(f"installed tail friction:  {installed_tail:.3f}  ({installed_phase.value})")
    print(f"friction delta (full v2): {delta:.3f}  rulings={rulings} resolved={resolved}")

    _, _, reduced_delta, _, reduced_resolved = measure(population, reduced_v2(ruleset))
    print(f"friction delta (v2 - R7): {reduced_delta:.3f}  resolved={reduced_resolved}")

    _, _, nonsense_delta, _, nonsense_resolved = measure(nonsense_population(population), ruleset)
    print(f"friction delta (nonsense): {nonsense_delta:.3f}  resolved={nonsense_resolved}")


if __name__ == "__main__":
    main()
